// Run npm run demo:record against a fresh local demo database.
// The browser uses the real backend and local Ollama, with labelled synthetic notes.
import { chromium } from "playwright";
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = process.cwd();
const videoDir = resolve(root, "demo/assets/video");
const screenshots = resolve(root, "demo/assets/screenshots");
mkdirSync(videoDir, { recursive: true });
mkdirSync(screenshots, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: "chrome" });
const context = await browser.newContext({ viewport: { width: 1920, height: 1080 }, recordVideo: { dir: videoDir, size: { width: 1920, height: 1080 } } });
const started = performance.now();
const scenes: {name:string; start:number; end?:number}[] = [];
function mark(name:string) {
  const now = (performance.now()-started)/1000;
  if (scenes.length) scenes[scenes.length-1].end = now;
  scenes.push({name, start:scenes.length?now:0});
}
const page = await context.newPage();
mark("problem");
await page.goto(process.env.DEMO_WEB_URL || "http://localhost:3001", { waitUntil: "networkidle" });
await page.waitForTimeout(8000);
await page.screenshot({ path: resolve(screenshots, "dashboard.png"), fullPage: true });
mark("import");
await page.getByRole("button", { name: "Import notes", exact: true }).click();
await page.locator("#import-box").fill(readFileSync(resolve(root,"demo/synthetic_research_notes.txt"),"utf8"));
await page.locator("#import-box").press("Control+Home");
await page.locator('input[type="datetime-local"]').fill("2026-10-21T09:00");
await page.getByRole("heading", {name:"Import notes",exact:true}).click();
await page.waitForTimeout(12000);
await page.screenshot({ path: resolve(screenshots, "input-notes.png"), fullPage: true });
mark("extraction");
const imported = page.waitForResponse(r => r.url().endsWith("/import"), { timeout: 300_000 });
await page.getByRole("button", { name: /find the promises/i }).click();
const response = await imported;
if (!response.ok()) throw new Error(`Real model import failed: ${response.status()}`);
await page.waitForTimeout(5000);
mark("evidence");
await page.screenshot({ path: resolve(screenshots, "evidence-review.png"), fullPage: true });
await page.waitForTimeout(12000);
await page.screenshot({ path: resolve(screenshots, "review-inbox.png"), fullPage: true });
mark("review");
const report = page.locator(".commit-card").filter({ hasText: /revised field report/i });
await report.getByRole("button", { name: /looks right/i }).click();
await page.waitForTimeout(6000);
await page.getByRole("button", { name: "Overview", exact:true }).click();
await page.waitForTimeout(10000);
await page.screenshot({ path: resolve(screenshots, "overdue-dashboard.png"), fullPage: true });
mark("followup");
await page.getByRole("button", { name: "Follow-ups", exact:true }).click();
await page.waitForTimeout(3000);
await page.getByRole("button", { name: /prepare draft/i }).first().click();
await page.waitForTimeout(13000);
await page.screenshot({ path: resolve(screenshots, "reviewed-follow-up.png"), fullPage: true });
mark("evaluation");
await page.getByRole("button", { name: "Privacy", exact:true }).click();
await page.waitForTimeout(8000);
mark("privacy");
await page.waitForTimeout(8000);
await page.screenshot({ path: resolve(screenshots, "privacy-controls.png"), fullPage: true });
scenes[scenes.length-1].end = (performance.now()-started)/1000;
const video = page.video();
if (!video) throw new Error("Playwright video recording did not start.");
await context.close();
await browser.close();
const webm = await video.path();
execFileSync("ffmpeg", ["-y", "-v","error", "-i", webm, "-an", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-movflags", "+faststart", resolve(videoDir, "demo_silent.mp4")], { stdio: "inherit" });
const duration = Number(execFileSync("ffprobe",["-v","error","-show_entries","format=duration","-of","default=noprint_wrappers=1:nokey=1",resolve(videoDir,"demo_silent.mp4")],{encoding:"utf8"}).trim());
scenes[scenes.length-1].end = duration;
writeFileSync(resolve(videoDir,"scene_timing.json"),JSON.stringify({synthetic:true,duration,scenes},null,2)+"\n");
console.log(`Recorded ${duration} seconds with genuine inference; scene_timing.json saved.`);
